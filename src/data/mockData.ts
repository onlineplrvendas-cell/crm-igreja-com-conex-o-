export function calculateWeeklySummary(entries: WeeklyConfirmationEntry[]): WeeklyConfirmationSummary {
  const total = entries.length;
  const confirmed = entries.filter(e => e.status === 'confirmed').length;
  const unconfirmed = entries.filter(e => e.status === 'unconfirmed').length;
  const confirmationRate = total > 0 ? Math.round((confirmed / total) * 100) : 0;

  const byCategory = {
    membros: entries.filter(e => e.category === 'Membro').length,
    visitantes: entries.filter(e => e.category === 'Visitante').length,
    convidados: entries.filter(e => e.category === 'Novo contato').length,
  };

  // Group top reasons
  const reasonMap: Record<string, number> = {};
  entries.forEach(e => {
    if (e.status === 'unconfirmed') {
      const r = (e.absenceReason || 'Não informado').split(' - ')[0].trim();
      reasonMap[r] = (reasonMap[r] || 0) + 1;
    }
  });

  const topReasons = Object.entries(reasonMap)
    .map(([reason, count]) => ({ reason, count }))
    .sort((a, b) => b.count - a.count);

  return {
    total,
    confirmed,
    unconfirmed,
    confirmationRate,
    byCategory,
    topReasons,
  };
}

